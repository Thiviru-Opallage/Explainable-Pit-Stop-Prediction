import time

def safe_get_json(url, max_retries=3, backoff=3):
    """GET a URL and return the JSON list. Retries on failure/non-200, returns [] only after exhausting retries."""
    for attempt in range(max_retries):
        try:
            resp = requests.get(url, timeout=15)
            if resp.status_code == 200:
                data = resp.json()
                return data if isinstance(data, list) else []
        except requests.exceptions.RequestException:
            pass
        time.sleep(backoff * (attempt + 1))  # 3s, 6s, 9s
    return []

def get_openf1_driver_lookup(session_key):
    """Map driver_number -> {code, team} for a given session, via OpenF1's /drivers endpoint."""
    drivers = safe_get_json(f"https://api.openf1.org/v1/drivers?session_key={session_key}")
    lookup = {}
    for d in drivers:
        lookup[str(d['driver_number'])] = {   # cast to str so lookups match regardless of type
            'code': d.get('name_acronym'),
            'team': d.get('team_name')
        }
    return lookup

# Convert race-control flag messages into a per-lap track status and attach
# the driver's running position using the corresponding timestamps.
FLAG_START_MESSAGES = {
    'SAFETY CAR': 'SAFETY CAR',
    'VIRTUAL SAFETY CAR': 'VIRTUAL SAFETY CAR',
    'RED FLAG': 'RED FLAG',
}
FLAG_END_MESSAGES = {'GREEN', 'CLEAR', 'TRACK CLEAR'}

def attach_race_control_and_position(df, session_key, base):
    rc = safe_get_json(f"{base}/race_control?session_key={session_key}")
    pos = safe_get_json(f"{base}/position?session_key={session_key}")

    df = df.copy()
    df['track_status'] = 'Green'
    df['position'] = None

    # Process race-control messages chronologically and maintain the current
    # track state. A safety-car or red-flag state remains active across laps
    # until a subsequent message indicates that normal racing has resumed.
    if rc:
        df_rc = pd.DataFrame(rc)
        df_rc['date'] = pd.to_datetime(df_rc['date'], format='ISO8601')
        df_rc = df_rc.sort_values('date')

        state_periods = []
        current_state = 'Green'
        state_start = None

        for _, row in df_rc.iterrows():
            msg = str(row.get('message', '')).upper()
            new_state = None
            for label, keyword in FLAG_START_MESSAGES.items():
                if keyword in msg:
                    new_state = label
                    break
            if new_state is None and any(k in msg for k in FLAG_END_MESSAGES):
                new_state = 'Green'
            if new_state is not None and new_state != current_state:
                if state_start is not None:
                    state_periods.append((state_start, row['date'], current_state))
                current_state = new_state
                state_start = row['date']

        if state_start is not None:
            state_periods.append((state_start, pd.Timestamp.max.tz_localize('UTC'), current_state))

        # Map each lap to the track-control state active at the start of that
        # lap. Laps without a valid timestamp are retained as Green by default.
        if state_periods and df['date_start'].notna().any():
            def status_for_time(t):
                if pd.isna(t):
                    return 'Green'
                for start, end, label in state_periods:
                    if start <= t < end:
                        return label
                return 'Green'
            df['track_status'] = df['date_start'].map(status_for_time)

    # Match each driver's lap timestamp with the nearest available position
    # record so that running position is aligned to the corresponding lap.
    if pos:
        df_pos = pd.DataFrame(pos)
        df_pos['date'] = pd.to_datetime(df_pos['date'], format='ISO8601')
        df_pos = df_pos.sort_values('date')

        has_time = df['date_start'].notna()
        # Remove the placeholder position column before the as-of merge to
        # ensure that the position returned by the position endpoint is kept
        # as the final position value.
        df_with_time = df[has_time].drop(columns=['position']).sort_values('date_start')
        df_no_time = df[~has_time].copy()

        merged = []
        for driver_num, group in df_with_time.groupby('driver_number'):
            driver_pos = df_pos[df_pos['driver_number'] == driver_num]
            if driver_pos.empty:
                group = group.copy()
                group['position'] = None
                merged.append(group)
                continue
            g = pd.merge_asof(
                group, driver_pos[['date', 'position']],
                left_on='date_start', right_on='date', direction='nearest'
            )
            merged.append(g)

        # Recombine the timestamp-matched and timestamp-missing records while
        # preserving all laps in the original dataset.
        df_with_time = pd.concat(merged, ignore_index=True) if merged else df_with_time
        df = pd.concat([df_with_time, df_no_time], ignore_index=True)

    return df

def get_openf1_race_data(session_key, year, round_number, event_name, jolpica_pits_2023=None):
    """Pull laps, stints, weather, pit, race_control, and position data for one race and merge into the unified schema."""
    base = "https://api.openf1.org/v1"

    laps = safe_get_json(f"{base}/laps?session_key={session_key}")
    if not laps:
        return pd.DataFrame()

    stints = safe_get_json(f"{base}/stints?session_key={session_key}")

    # Use Jolpica-F1 pit-stop data for 2023 because OpenF1's pit endpoint has
    # incomplete coverage for that season. For other seasons, use OpenF1's
    # native pit-stop endpoint.
    if year == 2023 and jolpica_pits_2023 is not None:
        pits = jolpica_pits_2023[jolpica_pits_2023['round'] == round_number].to_dict('records')
    else:
        pits = safe_get_json(f"{base}/pit?session_key={session_key}")

    df_laps = pd.DataFrame(laps)
    df_stints = pd.DataFrame(stints)
    df_pits = pd.DataFrame(pits)

    # Convert lap start timestamps to datetime so that lap records can be
    # aligned consistently with time-based weather, race-control, and position data.
    if 'date_start' in df_laps.columns:
        df_laps['date_start'] = pd.to_datetime(df_laps['date_start'], format='ISO8601')
    else:
        df_laps['date_start'] = pd.NaT

    # Expand each stint's lap range into individual lap records. This allows
    # tyre compound, stint number, and tyre life to be assigned to every lap.
    stint_rows = []
    for _, row in df_stints.iterrows():
        if pd.isna(row.get('lap_start')) or pd.isna(row.get('lap_end')):
            continue
        lap_start, lap_end = int(row['lap_start']), int(row['lap_end'])
        for lap_num in range(lap_start, lap_end + 1):
            stint_rows.append({
                'driver_number': row['driver_number'],
                'lap_number': lap_num,
                'compound': row['compound'],
                'stint': row['stint_number'],
                'tyre_life': lap_num - lap_start + row['tyre_age_at_start'] + 1
            })

    if stint_rows:
        df_stints_expanded = pd.DataFrame(stint_rows)
        df = df_laps.merge(df_stints_expanded, on=['driver_number', 'lap_number'], how='left')
    else:
        df = df_laps.copy()
        df['compound'] = None
        df['stint'] = None
        df['tyre_life'] = None

    if df.empty:
        return pd.DataFrame()

    # Identify pit-in laps by matching each driver's pit-stop lap against the
    # corresponding driver and lap number in the lap-level dataset.
    if not df_pits.empty:
        # Convert both driver and lap identifiers to integers before matching
        # because the two sources may represent these values using different
        # numeric types, which can otherwise prevent correct pit-lap matching.
        pit_keys = set(zip(df_pits['driver_number'].astype(int), df_pits['lap_number'].astype(int)))
        df['is_pit_lap'] = df.apply(
            lambda r: (int(r['driver_number']), int(r['lap_number'])) in pit_keys, axis=1
        )
    else:
        df['is_pit_lap'] = False

    # Retrieve weather observations and associate each lap with the closest
    # available weather measurement based on its start timestamp.
    weather = safe_get_json(f"{base}/weather?session_key={session_key}")
    if weather:
        df_weather = pd.DataFrame(weather)
        df_weather['date'] = pd.to_datetime(df_weather['date'], format='ISO8601')
        df_weather = df_weather.sort_values('date')

        has_time = df['date_start'].notna()
        df_with_time = df[has_time].sort_values('date_start')
        df_no_time = df[~has_time].copy()

        if not df_with_time.empty:
            df_with_time = pd.merge_asof(
                df_with_time, df_weather[['date', 'air_temperature', 'track_temperature', 'rainfall']],
                left_on='date_start', right_on='date', direction='nearest'
            )
        else:
            df_with_time['air_temperature'] = None
            df_with_time['track_temperature'] = None
            df_with_time['rainfall'] = None

        df_no_time['air_temperature'] = None
        df_no_time['track_temperature'] = None
        df_no_time['rainfall'] = None

        df = pd.concat([df_with_time, df_no_time], ignore_index=True)
    else:
        # Preserve the unified schema when no weather observations are available
        # by explicitly creating the expected weather columns with missing values.
        df['air_temperature'] = None
        df['track_temperature'] = None
        df['rainfall'] = None

    # Add race-control status and running position using the corresponding
    # OpenF1 race-control and position records.
    df = attach_race_control_and_position(df, session_key, base)

    driver_lookup = get_openf1_driver_lookup(session_key)

    # Map driver numbers to driver codes and team names, then construct the
    # unified schema used to combine OpenF1 data with the other data sources.
    result = pd.DataFrame({
        'season': year,
        'round': round_number,
        'event_name': event_name,
        'driver_number': df['driver_number'],
        'driver': df['driver_number'].map(lambda n: driver_lookup.get(str(int(n)), {}).get('code') if pd.notna(n) else None),
        'team': df['driver_number'].map(lambda n: driver_lookup.get(str(int(n)), {}).get('team') if pd.notna(n) else None),
        'lap_number': df['lap_number'],
        'lap_time_s': df['lap_duration'] if 'lap_duration' in df.columns else None,
        'compound': df['compound'],
        'tyre_life': df['tyre_life'],
        'stint': df['stint'],
        'is_pit_lap': df['is_pit_lap'],
        'track_status': df['track_status'],
        'air_temp': df['air_temperature'],
        'track_temp': df['track_temperature'],
        'rainfall': df['rainfall'],
        'position': df['position'],
        'data_source': 'openf1'
    })

    # Return the race-level data in the standardized schema so that it can be
    # combined consistently with data retrieved from FastF1 and Jolpica-F1.
    return result

def get_jolpica_pitstops_2023():
    """
    Pull real pit-stop data for the full 2023 season from Jolpica (Ergast successor),
    replacing OpenF1's /pit endpoint for this season only, since OpenF1 is missing
    pit data for 7 of 23 2023 races. Returns one DataFrame: driver_number, round,
    lap_number (the pit lap), ready to merge onto the 2023 laps table.
    """
    all_pits = []
    # Retrieve pit-stop records for each 2023 championship round. The round range
    # covers the 22 races in the 2023 season according to Jolpica's race schedule.
    for round_num in range(1, 23):  # 2023 season has 22 rounds, per Jolpica's own race list
        resp = requests.get(f"https://api.jolpi.ca/ergast/f1/2023/{round_num}/pitstops.json?limit=100")
        if resp.status_code != 200:
            print(f"Round {round_num}: request failed ({resp.status_code}), skipping")
            continue
        data = resp.json()
        races = data['MRData']['RaceTable']['Races']
        if not races:
            print(f"Round {round_num}: no race found, skipping")
            continue
        # Store each pit stop using the race round, Jolpica driver identifier,
        # and the lap on which the pit stop occurred.
        for stop in races[0]['PitStops']:
            all_pits.append({
                'round': round_num,
                'driverId': stop['driverId'],
                'lap_number': int(stop['lap'])
            })
        # Add a short delay between requests to reduce request frequency when
        # accessing Jolpica's free public API.
        time.sleep(0.5)

    df_pits_2023 = pd.DataFrame(all_pits)

    # Convert Jolpica's driverId values to permanent driver numbers, which match
    # the driver_number identifier used by OpenF1 and the unified dataset.
    unique_driver_ids = df_pits_2023['driverId'].unique()
    driver_number_map = {}
    for driver_id in unique_driver_ids:
        resp = requests.get(f"https://api.jolpi.ca/ergast/f1/drivers/{driver_id}.json")
        drivers = resp.json()['MRData']['DriverTable']['Drivers']
        if drivers and drivers[0].get('permanentNumber'):
            driver_number_map[driver_id] = int(drivers[0]['permanentNumber'])
        time.sleep(0.3)

    # Apply the driver identifier mapping and remove any pit-stop records for
    # which a corresponding permanent driver number could not be obtained.
    df_pits_2023['driver_number'] = df_pits_2023['driverId'].map(driver_number_map)
    df_pits_2023 = df_pits_2023.dropna(subset=['driver_number'])
    df_pits_2023['driver_number'] = df_pits_2023['driver_number'].astype(int)

    # Return only the fields required to match Jolpica pit stops to the
    # corresponding driver and lap in the OpenF1 2023 lap dataset.
    return df_pits_2023[['round', 'driver_number', 'lap_number']]

def build_openf1_season(year, races_for_year, drive_path='/content/drive/MyDrive/fyp_f1/data'):
    """Fetch and merge all races for one season via OpenF1, with rate-limit pacing and checkpointing."""

    out_path = f"{drive_path}/openf1_{year}.parquet"
    if os.path.exists(out_path):
        print(f"{year}: already saved, skipping. ({out_path})")
        return pd.read_parquet(out_path)

    # Fetch Jolpica's full 2023 pit-stop table once per season run, not once per race
    jolpica_pits_2023 = get_jolpica_pitstops_2023() if year == 2023 else None

    season_frames = []
    for i, race in enumerate(races_for_year):
        print(f"[{year}] Fetching round {i+1}/{len(races_for_year)}: {race['event_name']}")
        df_race = get_openf1_race_data(
            session_key=race['session_key'],
            year=race['year'],
            round_number=i + 1,
            event_name=race['event_name'],
            jolpica_pits_2023=jolpica_pits_2023
        )
        if not df_race.empty:
            season_frames.append(df_race)

        time.sleep(3)  # pacing between races

    if not season_frames:
        print(f"⚠ {year}: no usable races, skipping save.")
        return pd.DataFrame()

    df_season = pd.concat(season_frames, ignore_index=True)
    df_season.to_parquet(out_path, index=False)
    print(f"{year}: saved {len(df_season)} laps across {len(season_frames)} races -> {out_path}")
    return df_season

