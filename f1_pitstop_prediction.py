def build_sequences(X_df, y_series, meta_df, max_len=None):
    """Groups rows into per-(season,round,driver) sequences, ordered by lap.
    Returns padded X (samples, timesteps, features), padded y, and the max
    length used (so train's max_len can be reused for test)."""
    grouped = meta_df.assign(_idx=np.arange(len(meta_df))).groupby(
        ['season', 'round', 'driver']
    )['_idx'].apply(list)

    X_sequences, y_sequences = [], []
    for idx_list in grouped:
        X_sequences.append(X_df.iloc[idx_list].values)
        y_sequences.append(y_series.iloc[idx_list].values)

    if max_len is None:
        max_len = max(len(seq) for seq in X_sequences)

    X_padded = pad_sequences(X_sequences, maxlen=max_len, dtype='float32', padding='post', truncating='post')
    y_padded = pad_sequences(y_sequences, maxlen=max_len, dtype='float32', padding='post', truncating='post')

    return X_padded, y_padded, max_len

