    prev_lap = df['lap_number'] - window
    grp_driver = df.groupby(['season', 'round', 'driver'])
    # Calculate the driver's own position change relative to the position
    # recorded 2 or 3 laps earlier.
    df[f'own_position_trend_w{window}'] = df['position'] - grp_driver['position'].shift(window)

    for label, driver_col, pos_col in [
        ('ahead', 'driver_ahead', 'position_ahead'),
        ('behind', 'driver_behind', 'position_behind'),
    ]:
        # Step 1: identify which stint the neighbouring driver was using
        # N laps earlier rather than assuming their current stint was active.
        stint_keys = list(zip(df['season'], df['round'], df[driver_col], prev_lap))
        neighbor_prior_stint = stint_lookup.reindex(stint_keys).values

        # Step 2: use the neighbour's historical stint together with the
        # target lap to retrieve their actual position at that point in time.
        position_keys = list(zip(df['season'], df['round'], df[driver_col], neighbor_prior_stint, prev_lap))
        neighbor_prior_position = position_lookup.reindex(position_keys).values

        # Calculate the position difference between the current driver and
        # the neighbouring driver at the selected historical time point.
        df[f'{label}_position_trend_w{window}'] = df[pos_col] - neighbor_prior_position

