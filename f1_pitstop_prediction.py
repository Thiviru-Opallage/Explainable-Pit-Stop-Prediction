def masked_weighted_bce(y_true, y_pred, sample_weight):
    """Manually computes binary cross-entropy per timestep using the raw
    formula (not tf.keras.losses.binary_crossentropy, which collapses the
    last axis by default) - guarantees shape stays (batch, timesteps)
    throughout, so it always matches sample_weight's shape exactly."""
    epsilon = 1e-7
    y_pred = tf.clip_by_value(y_pred, epsilon, 1 - epsilon)  # avoid log(0)
    bce = -(y_true * tf.math.log(y_pred) + (1 - y_true) * tf.math.log(1 - y_pred))  # shape (batch, timesteps)
    weighted = bce * sample_weight
    return tf.reduce_sum(weighted) / (tf.reduce_sum(sample_weight) + 1e-8)

