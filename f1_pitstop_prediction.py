# Define a local exception for handling rate-limit conditions detected while
# accessing the FastF1 livetiming mirror. If FastF1 exposes a suitable
# rate-limit exception, that exception can be imported and used instead.
class RateLimitExceededError(Exception):
    """Raised when we detect we've been rate-limited by the FastF1 livetiming mirror."""
    pass

# Import FastF1's exception for sessions where data is unavailable. A fallback
# exception is defined to maintain compatibility if the exception is not
# available in the installed FastF1 version.
try:
    from fastf1._api import SessionNotAvailableError
except ImportError:
    class SessionNotAvailableError(Exception):
        pass


def build_fastf1_season(year, races_for_year, calls_per_race=9, hourly_budget=450):
    """Load one season's races with checkpointing to Drive."""
    out_path = OUTPUT_DIR / f'fastf1_{year}.parquet'
    if out_path.exists():
        print(f"Season {year} already saved at {out_path}, skipping.")
        return pd.read_parquet(out_path)

    pause_between = (3600 / hourly_budget) * calls_per_race
    season_dfs = []
    # Store failed races together with their round, name, and exception type
    # so that loading problems can be reviewed after the season is processed.
    failures = []  # (round, name, exception_type) for post-run diagnosis

    for i, race in enumerate(races_for_year):
        rnd, name = race['round'], race['event_name']
        try:
            df = load_fastf1_race(year, rnd)
            season_dfs.append(df)
            print(f"[{year} {i+1}/{len(races_for_year)}] OK: R{rnd} {name} ({len(df)} laps)")
            time.sleep(pause_between)

        except RateLimitExceededError:
            # If the mirror rate-limits a request, wait one hour before making
            # a single retry to avoid sending additional requests immediately.
            print(f"[{year} {i+1}/{len(races_for_year)}] Rate limit hit on R{rnd} {name} — waiting 60 min...")
            time.sleep(3600)
            try:
                df = load_fastf1_race(year, rnd)
                season_dfs.append(df)
                print(f"[{year} {i+1}/{len(races_for_year)}] OK (retry): R{rnd} {name}")
            except Exception as e:
                print(f"[{year} {i+1}/{len(races_for_year)}] FAILED after retry: R{rnd} {name} — {type(e).__name__}: {e}")
                failures.append((rnd, name, type(e).__name__))
            time.sleep(pause_between)

        except SessionNotAvailableError as e:
            # Record unavailable sessions separately from rate-limit and
            # unexpected errors because the cause is specific to the session.
            print(f"[{year} {i+1}/{len(races_for_year)}] NO DATA: R{rnd} {name} — {e}")
            failures.append((rnd, name, "SessionNotAvailableError"))
            time.sleep(pause_between)

        except Exception as e:
            # Catch and record unexpected errors so that one failed race does
            # not interrupt the processing of the remaining races.
            print(f"[{year} {i+1}/{len(races_for_year)}] FAILED: R{rnd} {name} — {type(e).__name__}: {e}")
            failures.append((rnd, name, type(e).__name__))
            time.sleep(pause_between)

    # Prevent an empty season file from being created if every race fails,
    # allowing the season to be safely retried once the data source is available.
    if not season_dfs:
        print(f"No races loaded for {year} — mirror may be down. Nothing saved; safe to retry later.")
        if failures:
            print(f"  Failure breakdown for {year}:")
            for rnd, name, err_type in failures:
                print(f"    R{rnd} {name}: {err_type}")
        return None

    season_df = pd.concat(season_dfs, ignore_index=True)
    season_df.to_parquet(out_path, index=False)
    print(f"Saved {year}: {len(season_df)} laps -> {out_path}")

    # Report any races that could not be loaded while still retaining the
    # successfully retrieved races in the season dataset.
    if failures:
        print(f"  {len(failures)} race(s) failed to load for {year}:")
        for rnd, name, err_type in failures:
            print(f"    R{rnd} {name}: {err_type}")

    return season_df


