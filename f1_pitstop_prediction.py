def build_bilstm(window_len, n_features):
    """Same architecture as the original full-race Bi-LSTM, minus Masking
    (not needed - every window is already a fixed length, no padding)."""
    return Sequential([
        Bidirectional(LSTM(64), input_shape=(window_len, n_features)),
        Dropout(0.3),
        Dense(32, activation='relu'),
        Dense(1, activation='sigmoid')
    ])

def train_and_evaluate(X_train_w, y_train_w, window_len, n_features,
                        epochs=30, patience=3, batch_size=32):
    """Trains one Bi-LSTM on windowed data with a held-out validation split
    and early stopping (same discipline as the original full-race model)."""
    model = build_bilstm(window_len, n_features)
    model.compile(optimizer=Adam(learning_rate=0.001), loss='binary_crossentropy')

    train_idx, val_idx = tts(np.arange(len(X_train_w)), test_size=0.15,
                              random_state=42, stratify=y_train_w)
    X_tr, X_val = X_train_w[train_idx], X_train_w[val_idx]
    y_tr, y_val = y_train_w[train_idx], y_train_w[val_idx]

    pos_weight = (y_tr == 0).sum() / (y_tr == 1).sum()
    sample_weight_tr = np.where(y_tr == 1, pos_weight, 1.0).astype('float32')

    best_val_loss = float('inf')
    epochs_no_improve = 0
    best_weights = None

    for epoch in range(epochs):
        history = model.fit(X_tr, y_tr, sample_weight=sample_weight_tr,
                             batch_size=batch_size, epochs=1, verbose=0)
        val_preds = model.predict(X_val, verbose=0).ravel()
        val_loss = tf.keras.losses.binary_crossentropy(y_val, val_preds).numpy().mean()

        train_loss = history.history['loss'][0]
        print(f"  Epoch {epoch+1}/{epochs} — train_loss: {train_loss:.4f}, val_loss: {val_loss:.4f}")

        if val_loss < best_val_loss:
            best_val_loss = val_loss
            epochs_no_improve = 0
            best_weights = model.get_weights()
        else:
            epochs_no_improve += 1
            if epochs_no_improve >= patience:
                print(f"  Early stopping at epoch {epoch+1} (best val_loss: {best_val_loss:.4f})")
                break

    model.set_weights(best_weights)

    val_preds_final = (model.predict(X_val, verbose=0).ravel() >= 0.5).astype(int)
    val_f1 = f1_score(y_val, val_preds_final)
    val_precision = precision_score(y_val, val_preds_final)
    val_recall = recall_score(y_val, val_preds_final)

    return model, {'val_f1': val_f1, 'val_precision': val_precision, 'val_recall': val_recall}

