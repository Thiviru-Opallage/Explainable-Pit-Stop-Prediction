# Step 1: create a lookup that identifies the stint used by each driver
# on each specific lap. This ensures that a neighbour's historical position
# is retrieved from the stint they were actually using at that time.
# If multiple stint records exist for the same driver and lap, retain the
# final recorded stint to represent the driver's settled state for that lap.
stint_lookup = (
    df.sort_values(['season', 'round', 'driver', 'lap_number', 'stint'])
    .drop_duplicates(subset=['season', 'round', 'driver', 'lap_number'], keep='last')
    .set_index(['season', 'round', 'driver', 'lap_number'])['stint']
)
n_stint_dupes = stint_lookup.index.duplicated().sum()
print(f"Stint lookup duplicate keys: {n_stint_dupes}")

# Step 2: create a lookup that maps each driver, stint, and lap to the
# corresponding race position. The previously identified historical stint
# is then used to retrieve the neighbour's position at the required lap.
position_lookup = df.set_index(['season', 'round', 'driver', 'stint', 'lap_number'])['position']
n_position_dupes = position_lookup.index.duplicated().sum()
print(f"Position lookup duplicate keys: {n_position_dupes}")

