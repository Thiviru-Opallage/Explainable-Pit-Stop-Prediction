def build_windowed_sequences(X_df, y_series, meta_df, window_len, lead_laps):
    """Slides a window_len-lap window (stride 1) over each (season,round,driver)
    sequence. Label = 1 if a pit lap occurs in the lead_laps laps right after
    the window. Returns X (num_windows, window_len, features) and y (num_windows,)."""
    grouped = meta_df.assign(_idx=np.arange(len(meta_df))).groupby(
        ['season', 'round', 'driver']
    )['_idx'].apply(list)

    X_windows, y_windows = [], []
    for idx_list in grouped:
        n_laps = len(idx_list)
        X_race = X_df.iloc[idx_list].values
        y_race = y_series.iloc[idx_list].values

        last_start = n_laps - window_len - lead_laps
        for start in range(0, last_start + 1):
            end = start + window_len
            label_slice = y_race[end:end + lead_laps]
            X_windows.append(X_race[start:end])
            y_windows.append(1 if label_slice.max() == 1 else 0)

    X_windowed = np.array(X_windows, dtype='float32')
    y_windowed = np.array(y_windows, dtype='float32')
    return X_windowed, y_windowed

